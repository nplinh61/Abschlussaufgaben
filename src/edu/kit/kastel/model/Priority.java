package edu.kit.kastel.model;

/**
 * Priority of a task.
 *
 * @author ukgot
 * @version 1.0
 */
public enum Priority {
    /**
     * Task with high priority.
     */
    HI,
    /**
     * Task with middle priority.
     */
 MD,
    /**
     * Task with low priority.
     */
 LO,
    /**
     * Task was not assigned with priority.
     */
 NONE
}
